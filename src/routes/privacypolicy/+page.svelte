    <h3>Two Different Roles</h3>
    <p>
      We handle data in two distinct roles, and your rights differ between them:
    </p>
    <p>
      <strong>Data we collect for ourselves.</strong> When you visit our websites, request a demo,
      start a trial, or do business with us, we decide how the resulting data is used, and this
      policy governs it directly.
    </p>
    <p>
      <strong>Your FullVue workspace.</strong> When a business subscribes to FullVue and creates a
      workspace, anything it puts into that workspace &mdash; employee records, customer lists,
      jobs, invoices, messages, files &mdash; belongs to that business and remains under its
      control. Each customer workspace runs against its own dedicated, isolated database. We only
      process workspace data on the customer&rsquo;s behalf and instructions, as described in
      Section 10 of the <a href="/subscription-agreement">FullVue Subscription Agreement</a>, and we
      never use it for advertising or sell it. If your data is in another business&rsquo;s FullVue
      workspace &mdash; for example, your employer or a company you hired &mdash; that business
      controls it, and privacy requests about it should go to that business; we will forward any
      request we receive to them promptly.
    </p>

    <h3>Personal Data We Collect</h3>
    <p><strong>Data you provide to us:</strong></p>
    <p style="padding-left: 1em;">
