      number (optional), company size, and the modules you select.
    </p>
    <p style="padding-left: 1em;">
      b) <strong>Contact and demo requests:</strong> name, company, email, phone (optional), and
      your message.
    </p>
    <p style="padding-left: 1em;">
      c) <strong>Billing and account management:</strong> the contact and billing details needed to
      administer a subscription. If and when payments are collected online, payment card details are
      collected and processed by a PCI-compliant payment processor and are not stored on our
      systems.
    </p>
    <p style="padding-left: 1em;">
      d) <strong>Support and correspondence:</strong> the contents of messages you send us.
    </p>
    <p><strong>Data collected automatically:</strong></p>
    <p style="padding-left: 1em;">
      e) <strong>Server logs:</strong> IP address, request details, and timestamps, used for
      security, rate limiting, and troubleshooting.
    </p>
    <p style="padding-left: 1em;">
      f) <strong>Analytics:</strong> we use Google Analytics to understand, in aggregate, how our
      websites are used (pages visited, approximate location, device type). See Cookies below.
