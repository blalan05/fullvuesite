    any time via the link in the email or by contacting us;</p>
    <p style="padding-left: 1em;">e) understand aggregate website usage to improve our products and
    content; and</p>
    <p style="padding-left: 1em;">f) comply with legal obligations and enforce our agreements.</p>
    <p>
      We do not use your personal data for targeted advertising, we do not sell it, and we do not
      combine it with data purchased from third parties.
    </p>

    <h3>When We Share Personal Data</h3>
    <p>
      We share personal data only with: service providers who process it on our behalf under
      contract, limited to what their role requires &mdash; website hosting and form processing
      (Netlify), analytics (Google), cloud infrastructure that hosts customer workspaces, email
      delivery, SMS delivery, and, when applicable, payment processing; professional advisors such
      as accountants and attorneys under confidentiality obligations; authorities when required by
      law or valid legal process, or to protect the rights, safety, or property of FoundTech, our
      customers, or others; and a successor in a merger, acquisition, or sale of assets, in which
      case this policy continues to apply. A current list of our service providers is available on
      request through our <a href="/contact">contact form</a>.
    </p>
    <p>
      All the above categories exclude text messaging originator opt-in data and consent; this
      information will not be shared with any third parties.
    </p>

    <h3>Cookies and Analytics</h3>
    <p>
      Our websites use a small number of cookies and similar technologies: Google Analytics cookies
      that help us understand aggregate site usage, and any cookies strictly necessary for a page to
      function. We do not use advertising or cross-site tracking cookies. You can block or clear
      cookies using your browser settings, and you can opt out of Google Analytics with
      Google&rsquo;s browser add-on; the site keeps working either way. Because some browsers&rsquo;
      &ldquo;Do Not Track&rdquo; signals have no common standard, our sites do not respond to them
      &mdash; but since we do not sell personal data or track you across other sites, there is
      nothing such a signal would need to switch off.
    </p>

