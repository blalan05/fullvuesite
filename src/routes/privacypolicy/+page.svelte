    <p>We use the data above to:</p>
    <p style="padding-left: 1em;">a) provide, secure, and troubleshoot our websites and the FullVue
    service, including provisioning trial workspaces;</p>
    <p style="padding-left: 1em;">b) respond to your requests and provide support;</p>
    <p style="padding-left: 1em;">c) administer accounts, billing, and renewals, including required
    renewal reminders;</p>
    <p style="padding-left: 1em;">d) send service and account communications, and &mdash; if you
